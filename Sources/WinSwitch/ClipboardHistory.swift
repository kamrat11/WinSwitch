import AppKit

/// Clipboard history (Win+V), like Windows: the last 25 copies plus pinned items. Unpinned items live only in memory,
/// as on Windows they are gone after a restart; pinned ones are saved in Application Support. Copies that password
/// managers mark as concealed or transient are never recorded.
@MainActor
final class ClipboardHistory {
    static let shared = ClipboardHistory()

    struct Entry: Codable, Identifiable {
        let id: UUID
        var date: Date
        var pinned: Bool
        /// One dictionary per pasteboard item (several for multiple files): type -> data.
        let items: [[String: Data]]

        var text: String? {
            items.first?[NSPasteboard.PasteboardType.string.rawValue].flatMap { String(data: $0, encoding: .utf8) }
        }
        var fileURLs: [URL] {
            items.compactMap { $0[NSPasteboard.PasteboardType.fileURL.rawValue] }
                .compactMap { String(data: $0, encoding: .utf8).flatMap(URL.init(string:)) }
        }
        var image: NSImage? {
            guard fileURLs.isEmpty, let item = items.first else { return nil }
            let data = item[NSPasteboard.PasteboardType.png.rawValue] ?? item[NSPasteboard.PasteboardType.tiff.rawValue]
            return data.flatMap(NSImage.init(data:))
        }
    }

    private(set) var entries: [Entry] = []
    var onChange: (() -> Void)?

    static let maxUnpinned = 25
    nonisolated private static let maxEntryBytes = 20 * 1024 * 1024
    nonisolated private static let kept: [NSPasteboard.PasteboardType] = [.string, .rtf, .html, .png, .tiff, .fileURL, .URL]
    nonisolated private static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private var folder: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("WinSwitch/Clipboard", isDirectory: true)
    }
    private var pinnedFile: URL { folder.appendingPathComponent("pinned.plist") }

    func start() {
        guard timer == nil else { return }
        if let data = try? Data(contentsOf: pinnedFile),
           let pinned = try? PropertyListDecoder().decode([Entry].self, from: data) {
            entries = pinned
        }
        // macOS has no clipboard notification; checking the change counter twice a second is what clipboard
        // managers do, and costs next to nothing.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardHistory.shared.poll() }
        }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard Settings.clipboardHistoryEnabled else { return }
        // Reading can block for seconds when the copying app is slow or has quit with data still promised, so it
        // happens off the main thread, which must stay free for the keyboard hook.
        Self.readQueue.async {
            guard let items = Self.read(NSPasteboard.general) else { return }
            DispatchQueue.main.async {
                MainActor.assumeIsolated { ClipboardHistory.shared.add(items) }
            }
        }
    }

    private static let readQueue = DispatchQueue(label: "WinSwitch.clipboard")

    /// The kept types of every pasteboard item, or nil for secret, empty or oversized copies.
    nonisolated private static func read(_ pasteboard: NSPasteboard) -> [[String: Data]]? {
        guard let pbItems = pasteboard.pasteboardItems, !pbItems.isEmpty else { return nil }
        if pbItems.contains(where: { $0.types.contains { skipped.contains($0.rawValue) } }) { return nil }
        var total = 0
        let items: [[String: Data]] = pbItems.map { item in
            var dict: [String: Data] = [:]
            for type in kept where item.types.contains(type) {
                if let data = item.data(forType: type) { dict[type.rawValue] = data; total += data.count }
            }
            return dict
        }.filter { !$0.isEmpty }
        return items.isEmpty || total > maxEntryBytes ? nil : items
    }

    private func add(_ items: [[String: Data]]) {
        // Copying something that is already in the list moves it to the top (keeping its pin).
        var pinned = false
        if let existing = entries.firstIndex(where: { $0.items == items }) {
            pinned = entries[existing].pinned
            entries.remove(at: existing)
        }
        entries.insert(Entry(id: UUID(), date: Date(), pinned: pinned, items: items), at: 0)
        trim()
        if pinned { save() }
        onChange?()
    }

    /// Puts an entry back on the clipboard.
    func copy(_ entry: Entry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.writeObjects(entry.items.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            return item
        })
    }

    func togglePin(_ id: UUID) {
        guard let i = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[i].pinned.toggle()
        trim()
        save()
        onChange?()
    }

    func delete(_ id: UUID) {
        let wasPinned = entries.first { $0.id == id }?.pinned ?? false
        entries.removeAll { $0.id == id }
        if wasPinned { save() }
        onChange?()
    }

    /// "Clear all" keeps the pinned items, as on Windows.
    func clearUnpinned() {
        entries.removeAll { !$0.pinned }
        onChange?()
    }

    private func trim() {
        var unpinned = 0
        entries.removeAll { entry in
            guard !entry.pinned else { return false }
            unpinned += 1
            return unpinned > Self.maxUnpinned
        }
    }

    private func save() {
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let encoder = PropertyListEncoder()
        encoder.outputFormat = .binary
        if let data = try? encoder.encode(entries.filter(\.pinned)) {
            try? data.write(to: pinnedFile, options: [.atomic, .completeFileProtection])
        }
    }
}
