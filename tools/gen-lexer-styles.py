#!/usr/bin/env python3
"""Writes Sources/WinCode/LexerStyles.swift: for every Lexilla lexer, which kind of token each style number is.

The kinds come from the style names in SciLexer.h (SCE_CSS_COMMENT is a comment, SCE_SQL_WORD a keyword...), so one
WinCode theme colours all lexers. Run from the repo root after updating Vendor/Scintilla: python3 tools/gen-lexer-styles.py
"""
import glob, re

V = "Vendor/Scintilla"
names = {}  # lexer name -> SCLEX_
for path in glob.glob(f"{V}/lexilla/lexers/*.cxx"):
    for m in re.finditer(r'LexerModule\s+\w+\(\s*(SCLEX_\w+)\s*,[^"]*?"([^"]+)"', open(path, encoding="latin-1").read()):
        names[m.group(2)] = m.group(1)
prefixes = {}  # SCLEX_ -> [SCE_ prefixes]
for m in re.finditer(r"^lex \w+=(SCLEX_\w+)(.*)$", open(f"{V}/lexilla/include/LexicalStyles.iface").read(), re.M):
    prefixes.setdefault(m.group(1), []).extend(m.group(2).split())
styles = {}  # prefix -> [(number, suffix)]
for m in re.finditer(r"^#define (SCE_\w+?_)?(\w+) (\d+)$", open(f"{V}/include/SciLexer.h").read(), re.M):
    pass
defines = re.findall(r"^#define (SCE_\w+) (\d+)$", open(f"{V}/include/SciLexer.h").read(), re.M)

RULES = [  # first match wins; checked against the part after the prefix
    ("added", r"^ADDED|PATCH_ADD"), ("deleted", r"^DELETED|PATCH_DELETE"), ("changed", r"^CHANGED"),
    ("commentDoc", r"COMMENT.*DOC|DOC.*COMMENT|^DOCSTRING|COMMENTDOC"),
    ("comment", r"COMMENT|^REM$"),
    ("error", r"ERROR|^BAD|STRINGEOL|UNKNOWN|UNCLOSED"),
    ("regex", r"REGEX"),
    ("heading", r"^HEAD|HEADER|HEADING|^H\d$|SECTION|^TITLE|^POSITION$|^COMMAND$"),
    ("link", r"LINK|URL|^URI"),
    ("emphasis", r"STRONG|^EM\d|BOLD|ITALIC|EMPH"),
    ("preprocessor", r"PREPROC|DIRECTIVE|PRAGMA|^MACRO|^DEFINE|^IMPORT|^INCLUDE"),
    ("string", r"STRING|CHARACTER|^CHAR|TRIPLE|VERBATIM|HEREDOC|BACKTICK|QUOTE|LITERAL|^SQ|^DQ|^CDATA|^TEXT$|^VALUE$|^CODE"),
    ("number", r"NUMBER|NUMERIC|^NUM|^HEX|FLOAT|INTEGER|^DATE|^DECIMAL|^BINARY|^OCTAL"),
    ("operator", r"OPERATOR|^OPER|PUNCT|DELIMITER|^BRACE|^BRACKET|^SYMBOL"),
    ("tag", r"^TAG|ELEMENT|^XMLSTART|^XMLEND|^SGML_"),
    ("attribute", r"ATTRIBUTE|^ATTR|PROPERTY|^KEY|^ASSIGNMENT|^PARAMETER$"),
    ("entity", r"ENTITY|ESCAPE"),
    ("type", r"WORD2|KEYWORD2|WORD3|^TYPE|CLASS|^STRUCT|^INTERFACE|^ENUM|^UUID|^GLOBALCLASS"),
    ("function", r"DEFNAME|FUNCNAME|^FUNCTION|^METHOD|^DECORATOR|^BUILTIN|^IDENTIFIER2"),
    ("keyword", r"WORD|KEYWORD|INSTRUCTION|^CPU|^STATEMENT|^RESERVED|^CMD|^OPCODE|^REGISTER|^DIRECTIVE"),
    ("label", r"LABEL|^SECTIONNAME|^TARGET"),
    ("variable", r"VARIABLE|SCALAR|^ARRAY|^HASH|^PARAM|^VAR|^SYMBOL|^ENV"),
]

out = ["// Generated by tools/gen-lexer-styles.py from Lexilla's SciLexer.h; do not edit.",
       "", "/// Style number -> token kind for each Lexilla lexer, so one theme colours them all.",
       "enum LexerStyles {", "    static let table: [String: [Int: TokenKind]] = ["]
for name in sorted(names):
    sclex = names[name]
    entries = {}
    for prefix in prefixes.get(sclex, []):
        for define, number in defines:
            if not define.startswith(prefix):
                continue
            suffix = define[len(prefix):]
            if suffix == "DEFAULT":
                continue
            for kind, pattern in RULES:
                if re.search(pattern, suffix):
                    entries.setdefault(int(number), kind)
                    break
    if entries:
        body = ", ".join(f"{n}: .{k}" for n, k in sorted(entries.items()))
        out.append(f'        "{name}": [{body}],')
out += ["    ]", "}", ""]
open("Sources/WinCode/LexerStyles.swift", "w").write("\n".join(out))
print(f"{len(out) - 7} lexers")
